import { generateSchema, type JsonSchema } from './schemaGen';

type Schema = Record<string, unknown>;

const ROOT = 'CharacterStats';
/** Exported name of the root definition; consumers know the file as CharacterStatInfo. */
const rename = (name: string): string => (name === ROOT ? 'CharacterStatInfo' : name);

const isSchema = (value: unknown): value is Schema =>
    typeof value === 'object' && value !== null && !Array.isArray(value);

function comment(description: unknown, indent: string): string {
    if (typeof description !== 'string' || !description) return '';
    const text = description.replaceAll('*/', '*\\/');
    const lines: string[] = [];
    let line = '';
    for (const word of text.split(/\s+/)) {
        if (line && indent.length + line.length + word.length + 4 > 100) {
            lines.push(line);
            line = '';
        }
        line += (line ? ' ' : '') + word;
    }
    lines.push(line);
    return lines.length === 1
        ? `${indent}/** ${lines[0]} */\n`
        : `${indent}/**\n${lines.map((entry) => `${indent} * ${entry}`).join('\n')}\n${indent} */\n`;
}

const key = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

/** Converts the schema features that generateSchema uses into a TypeScript type expression. */
function tsType(schema: Schema, indent: string): string {
    if (typeof schema.$ref === 'string') return rename(schema.$ref.replace('#/definitions/', ''));
    if (Array.isArray(schema.enum)) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
    switch (schema.type) {
        case 'string':
            return 'string';
        case 'integer':
        case 'number':
            return 'number';
        case 'array': {
            const item = isSchema(schema.items) ? tsType(schema.items, indent) : 'unknown';
            return /^[\w.]+$/.test(item) ? item + '[]' : `Array<${item}>`;
        }
        case 'object':
            return objectType(schema, indent);
        default:
            throw new Error('Unsupported schema for declarations: ' + JSON.stringify(schema));
    }
}

function objectType(schema: Schema, indent: string): string {
    const properties = isSchema(schema.properties) ? schema.properties : {};
    const required = new Set(Array.isArray(schema.required) ? schema.required : []);
    const inner = indent + '    ';
    const body = Object.entries(properties).map(([name, value]) => {
        const property = value as Schema;
        return (
            comment(property.description, inner) +
            `${inner}${key(name)}${required.has(name) ? '' : '?'}: ${tsType(property, inner)};\n`
        );
    });
    return `{\n${body.join('')}${indent}}`;
}

const header = `// Generated by \`npm run schema\` from the registries in src/core. Do not edit by hand.
// Types for the published Destiny 2 Character Stats files (see README.md).
// Usage: import type { CharacterStatInfo, UpdateInfo } from './character-stats';

`;

const updateInfo = `/** Contents of update.json, which tells consumers whether newer data is available. */
export interface UpdateInfo {
    /**
     * Unix epoch time in nanoseconds of the last database update. It is larger than
     * Number.MAX_SAFE_INTEGER, so a parsed value is approximate: only compare it for change.
     */
    lastUpdate: number;
    /** Schema version: full X.Y.Z for v2 and later (legacy v1 uses X.Y). */
    schemaVersion: string;
}
`;

/** TypeScript declarations for CharacterStatInfo.json (and update.json), from the JSON schema. */
export function generateDeclarations(schema: JsonSchema = generateSchema()): string {
    const definitions = isSchema(schema.definitions) ? schema.definitions : {};
    const blocks = Object.entries(definitions).map(([name, value]) => {
        const definition = value as Schema;
        const doc = comment(definition.description, '');
        const exported = rename(name);
        return definition.type === 'object' && isSchema(definition.properties)
            ? `${doc}export interface ${exported} ${objectType(definition, '')}\n`
            : `${doc}export type ${exported} = ${tsType(definition, '')};\n`;
    });
    return header + blocks.join('\n') + '\n' + updateInfo;
}
